const legalSuffix = /\b(?:company|co|limited|ltd|plc|incorporated|inc)\b/gi;

export function normalizeText(value: unknown) {
  return String(value ?? "")
    .normalize("NFKC")
    .replace(/\p{Cc}/gu, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function simpleKey(value: string) {
  return value
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function titleCase(value: string) {
  const keep = new Set([
    "ESCOM",
    "EGENCO",
    "PPDA",
    "NOCMA",
    "MACRA",
    "CMST",
    "TEVETA",
    "MRA",
    "MERA",
    "TNM",
    "FDH",
    "NBS",
    "JTI",
    "SICPA",
  ]);
  return value
    .toLowerCase()
    .replace(/\b\w/g, (letter) => letter.toUpperCase())
    .split(" ")
    .map((word) => (keep.has(word.toUpperCase()) ? word.toUpperCase() : word))
    .join(" ");
}

export function canonicalCompany(value: unknown) {
  const cleaned = normalizeText(value).replace(/\s+([,.)])/g, "$1");
  const direct = aliases[simpleKey(cleaned)];
  if (direct) return direct;
  const withoutSuffix = normalizeText(
    cleaned.replace(legalSuffix, " ").replace(/\bmalawi\b/gi, " "),
  );
  const suffixAlias = aliases[simpleKey(withoutSuffix)];
  if (suffixAlias) return suffixAlias;
  return titleCase(cleaned);
}

export function companyKey(value: unknown) {
  const canonical = canonicalCompany(value);
  return simpleKey(canonical.replace(legalSuffix, " ").replace(/\bmalawi\b/gi, " "));
}

export function normalizePhone(value: unknown) {
  const raw = normalizeText(value);
  if (!raw) return "";
  const candidates = raw
    .split(/\s*(?:\/|,|\bor\b|&|;)\s*/i)
    .map((part) => part.replace(/\D/g, ""))
    .filter(Boolean);
  for (let digits of candidates) {
    if (digits.startsWith("265") && digits.length === 12) digits = `0${digits.slice(3)}`;
    else if (digits.length === 9) digits = `0${digits}`;
    else if (digits.length === 10 && !digits.startsWith("0")) digits = `0${digits.slice(-9)}`;
    if (/^0\d{9}$/.test(digits)) return digits;
  }
  return "";
}

export function normalizeGender(value: unknown) {
  const gender = normalizeText(value).toLowerCase();
  if (gender.startsWith("f")) return "Female";
  if (gender.startsWith("m")) return "Male";
  return gender ? titleCase(gender) : "";
}

export function normalizeName(value: unknown) {
  const name = normalizeText(value);
  return name === name.toUpperCase() ? titleCase(name) : name;
}
